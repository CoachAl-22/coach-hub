import unittest
from datetime import date, timedelta

from database import get_db, _ensure_term4_run_club
from services.session_schedule import is_within_effective_session_bounds


class Term4RunClubTests(unittest.TestCase):
    """Use connection-local temporary tables, never the actual roster tables."""

    def setUp(self):
        self.db = get_db()
        self.addCleanup(self.db.close)
        self.db.execute('''
            CREATE TEMP TABLE sessions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                day_of_week TEXT, start_time TEXT, end_time TEXT, location TEXT,
                programs TEXT, min_coaches INTEGER, max_coaches INTEGER,
                notes TEXT, is_active INTEGER
            ) ON COMMIT DROP
        ''')
        self.db.execute('''
            CREATE TEMP TABLE terms (
                id INTEGER PRIMARY KEY, start_date TEXT, end_date TEXT
            ) ON COMMIT DROP
        ''')
        self.db.execute('''
            CREATE TEMP TABLE session_overrides (
                session_id INTEGER, term_id INTEGER, start_date TEXT, end_date TEXT,
                PRIMARY KEY (session_id, term_id)
            ) ON COMMIT DROP
        ''')
        self.db.execute('''
            CREATE TEMP TABLE roster_entries (
                session_id INTEGER, term_id INTEGER, coach_id INTEGER, date TEXT
            ) ON COMMIT DROP
        ''')
        self.db.execute('''
            INSERT INTO terms VALUES
                (3, '2026-07-13', '2026-09-25'),
                (4, '2026-10-05', '2026-12-18'),
                (5, '2027-01-25', '2027-03-26')
        ''')
        self.db.execute('''
            INSERT INTO sessions
                (id, day_of_week, start_time, end_time, location, programs, is_active)
            VALUES (100, 'Tuesday', '07:00', '08:15',
                    'Peninsula Grammar', 'School Program', 1)
        ''')
        self.db.execute('''
            INSERT INTO session_overrides VALUES (100, 4, NULL, '2026-10-04')
        ''')

    def club(self):
        return self.db.execute(
            "SELECT * FROM sessions WHERE programs='Run Club'"
        ).fetchone()

    def test_exact_seven_tuesdays_and_term4_only(self):
        _ensure_term4_run_club(self.db, 4)
        club = self.club()
        self.assertEqual(
            (club['day_of_week'], club['start_time'], club['end_time'], club['location']),
            ('Tuesday', '07:00', '08:30', 'Peninsula Grammar'),
        )
        self.assertEqual(club['min_coaches'], 1)
        for term in self.db.execute('SELECT * FROM terms').fetchall():
            override = self.db.execute(
                'SELECT * FROM session_overrides WHERE session_id=%s AND term_id=%s',
                (club['id'], term['id']),
            ).fetchone()
            day = date.fromisoformat(term['start_date'])
            occurrences = []
            while day <= date.fromisoformat(term['end_date']):
                if day.weekday() == 1 and is_within_effective_session_bounds(
                    day, term['start_date'], term['end_date'], override
                ):
                    occurrences.append(day.isoformat())
                day += timedelta(days=1)
            self.assertEqual(occurrences, [
                '2026-10-27', '2026-11-03', '2026-11-10', '2026-11-17',
                '2026-11-24', '2026-12-01', '2026-12-08',
            ] if term['id'] == 4 else [])

    def test_repeated_setup_preserves_assignments_and_historical_session(self):
        _ensure_term4_run_club(self.db, 4)
        club_id = self.club()['id']
        self.db.execute(
            'INSERT INTO roster_entries VALUES (%s, 4, 999, %s)',
            (club_id, '2026-10-27'),
        )
        # Also upgrade an existing Run Club that previously required two coaches.
        self.db.execute('UPDATE sessions SET min_coaches=2 WHERE id=%s', (club_id,))
        _ensure_term4_run_club(self.db, 4)
        self.assertEqual(self.club()['id'], club_id)
        self.assertEqual(self.club()['min_coaches'], 1)
        self.assertEqual(self.db.execute(
            "SELECT COUNT(*) AS count FROM sessions WHERE programs='Run Club'"
        ).fetchone()['count'], 1)
        self.assertEqual(self.db.execute(
            'SELECT COUNT(*) AS count FROM roster_entries WHERE session_id=%s',
            (club_id,),
        ).fetchone()['count'], 1)
        old = self.db.execute('SELECT * FROM sessions WHERE id=100').fetchone()
        self.assertEqual(old['end_time'], '08:15')
        self.assertEqual(self.db.execute(
            'SELECT end_date FROM session_overrides WHERE session_id=100 AND term_id=4'
        ).fetchone()['end_date'], '2026-10-04')

        # The legacy school exclusion must not match and clear Run Club staff.
        legacy = self.db.execute(
            """SELECT id FROM sessions
               WHERE day_of_week='Tuesday' AND start_time='07:00'
                 AND location ILIKE %s
                 AND (programs IS DISTINCT FROM 'Run Club' OR end_time <> '08:30')""",
            ('%Peninsula Grammar%',),
        ).fetchall()
        self.assertEqual([row['id'] for row in legacy], [100])


if __name__ == '__main__':
    unittest.main()
